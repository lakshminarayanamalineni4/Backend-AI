# Directory used for persisted AI retrieval artifacts.
#
# This is intentionally separate from the Python source code so that
# generated indexes are treated as runtime/build artifacts.
VECTOR_STORE_DIR = (
    Path(__file__).resolve().parents[1]
    / "vector_store"
)

# Persisted BM25 index.
BM25_INDEX_PATH = (
    VECTOR_STORE_DIR / "bm25.pkl"
)


# ---------------------------------------------------------------------------
# Tokenisation
# ---------------------------------------------------------------------------

def tokenize(text: str) -> list[str]:
    """
    Convert text into a list of normalized tokens.

    BM25 works with tokenized documents rather than raw strings.

    Example:

        "Cashback is credited within 48 hours"

    becomes approximately:

        [
            "cashback",
            "is",
            "credited",
            "within",
            "48",
            "hours",
        ]

    The tokenisation strategy is intentionally simple for now.
    A production system could later introduce:

    - stemming
    - lemmatization
    - stop-word handling
    - language-specific tokenization
    - domain-specific normalization
    """

    if not text:
        return []

    return re.findall(
        r"\b\w+\b",
        text.lower(),
    )


# ---------------------------------------------------------------------------
# BM25 Sparse Vector Store
# ---------------------------------------------------------------------------

class BM25VectorStore:
    """
    Persistent BM25-based sparse retrieval store.

    Responsibilities:

    1. Build a BM25 index from document chunks.
    2. Persist the index and metadata.
    3. Load the persisted index.
    4. Search for relevant chunks.
    5. Map BM25 results back to their original metadata.

    The store is intentionally independent from FAISS.

    FAISS handles dense semantic retrieval.

    BM25 handles sparse lexical retrieval.

    Both systems operate over the same chunk collection.
    """

    def __init__(
        self,
        index_path: Path = BM25_INDEX_PATH,
    ):
        """
        Initialize the BM25 vector store.

        Parameters
        ----------
        index_path:
            Location where the persisted BM25 artifact is stored.
        """

        self.index_path = Path(
            index_path
        )

        self.bm25: BM25Okapi | None = None

        self.metadata: list[dict[str, Any]] = []

    # -----------------------------------------------------------------------
    # Build
    # -----------------------------------------------------------------------

    def build(
        self,
        chunks: list[dict],
    ) -> None:
        """
        Build a BM25 index from metadata-aware chunks.

        Parameters
        ----------
        chunks:
            List of chunk dictionaries generated by create_chunks().

        Expected structure:

            {
                "text": "...",
                "metadata": ChunkMetadata(...)
            }

        The order of the BM25 corpus and metadata list is kept identical.

        This is critical because BM25 returns integer document positions.
        Those positions are then used to map search results back to the
        original chunk metadata.
        """

        if not chunks:
            raise ValueError(
                "Cannot build BM25 index from empty chunks."
            )

        # Extract the text from every chunk.
        texts = [
            chunk["text"]
            for chunk in chunks
        ]

        # Tokenize every document for BM25.
        tokenized_corpus = [
            tokenize(text)
            for text in texts
        ]

        # Build the in-memory BM25 index.
        self.bm25 = BM25Okapi(
            tokenized_corpus
        )

        # Store the original chunks so that BM25 result positions
        # can be mapped back to the original text and metadata.
        self.metadata = chunks

    # -----------------------------------------------------------------------
    # Save
    # -----------------------------------------------------------------------

    def save(self) -> None:
        """
        Persist the BM25 index and metadata to disk.

        The persisted artifact contains:

        - BM25 model
        - original metadata-aware chunks

        This allows the application to load the retrieval index without
        rebuilding it from the original documents on every startup.
        """

        if self.bm25 is None:
            raise RuntimeError(
                "BM25 index has not been built."
            )

        if not self.metadata:
            raise RuntimeError(
                "BM25 metadata is empty."
            )

        # Ensure the parent directory exists.
        self.index_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        payload = {
            "bm25": self.bm25,
            "metadata": self.metadata,
        }

        with self.index_path.open(
            "wb"
        ) as file:
            pickle.dump(
                payload,
                file,
            )

    # -----------------------------------------------------------------------
    # Load
    # -----------------------------------------------------------------------

    def load(self) -> None:
        """
        Load a persisted BM25 index from disk.
        """

        if not self.index_path.exists():
            raise FileNotFoundError(
                "BM25 index not found at "
                f"{self.index_path}. "
                "Build and persist the index first."
            )

        with self.index_path.open(
            "rb"
        ) as file:
            payload = pickle.load(
                file
            )

        if not isinstance(
            payload,
            dict,
        ):
            raise RuntimeError(
                "Invalid BM25 index format."
            )

        self.bm25 = payload.get(
            "bm25"
        )

        self.metadata = payload.get(
            "metadata",
            [],
        )

        if self.bm25 is None:
            raise RuntimeError(
                "Persisted BM25 index is invalid."
            )

        if not self.metadata:
            raise RuntimeError(
                "Persisted BM25 metadata is empty."
            )

    # -----------------------------------------------------------------------
    # Search
    # -----------------------------------------------------------------------

    def search(
        self,
        query: str,
        top_k: int = 5,
    ) -> list[dict]:
        """
        Search the BM25 index.

        Parameters
        ----------
        query:
            User's natural-language query.

        top_k:
            Maximum number of results to return.

        Returns
        -------
        list[dict]
            Retrieved chunks with BM25 scores.

        Example result:

            {
                "text": "...",
                "metadata": ChunkMetadata(...),
                "score": 8.42,
            }
        """

        if self.bm25 is None:
            raise RuntimeError(
                "BM25 index is not loaded."
            )

        if not query or not query.strip():
            raise ValueError(
                "Search query cannot be empty."
            )

        if top_k <= 0:
            raise ValueError(
                "top_k must be greater than zero."
            )

        # Tokenize the user query using the exact same
        # tokenization strategy used during indexing.
        query_tokens = tokenize(
            query
        )

        if not query_tokens:
            return []

        # BM25 returns one relevance score for every indexed document.
        scores = self.bm25.get_scores(
            query_tokens
        )

        # Sort document positions by score in descending order.
        ranked_indices = sorted(
            range(
                len(scores)
            ),
            key=lambda index: scores[index],
            reverse=True,
        )

        results = []

        # Return only the requested number of results.
        for index in ranked_indices[
            :top_k
        ]:

            chunk = self.metadata[
                index
            ]

            results.append(
                {
                    "text": chunk["text"],
                    "metadata": chunk[
                        "metadata"
                    ],
                    "score": float(
                        scores[index]
                    ),
                }
            )

        return results


# ---------------------------------------------------------------------------
# BM25 Search Service
# ---------------------------------------------------------------------------

class BM25SearchService:
    """
    Service responsible for sparse lexical document retrieval.

    Wraps the persisted BM25 vector store and exposes a
    search API that mirrors DocumentSearchService so hybrid
    retrieval can call both systems uniformly.
    """

    def __init__(
        self,
        vector_store: BM25VectorStore,
    ):
        """
        Initialize the BM25 search service.

        Parameters
        ----------
        vector_store:
            Persistent BM25 store used for lexical search.
            The index must already be loaded.
        """

        self.vector_store = vector_store

    def search(
        self,
        query: str,
        top_k: int = 5,
    ) -> list[dict]:
        """
        Search the BM25 index for relevant chunks.

        Parameters
        ----------
        query:
            User's natural-language query.

        top_k:
            Maximum number of results to return.

        Returns
        -------
        list[dict]
            Retrieved chunks with BM25 scores.
        """

        return self.vector_store.search(
            query=query,
            top_k=top_k,
        )


@lru_cache(maxsize=1)
def get_sparse_search_service() -> BM25SearchService:
    """
    Create and cache a reusable BM25 search service.

    The BM25 index is loaded once per process and reused
    across hybrid and sparse retrieval calls.
    """

    vector_store = BM25VectorStore()
    vector_store.load()

    return BM25SearchService(
        vector_store=vector_store,
    )


# ---------------------------------------------------------------------------
# Build and persist BM25 index
# ---------------------------------------------------------------------------

def build_bm25_index() -> None:
    """
    Build and persist the BM25 index.

    This function represents the offline indexing process.

    It should be executed when:

    - Documents are added.
    - Documents are updated.
    - Chunking logic changes.
    - Tokenization logic changes.
    """

    print(
        "Loading documents and creating chunks..."
    )

    chunks = create_chunks()

    print(
        f"Total chunks: {len(chunks)}"
    )

    vector_store = BM25VectorStore()

    print(
        "Building BM25 index..."
    )

    vector_store.build(
        chunks
    )

    print(
        "Saving BM25 index..."
    )

    vector_store.save()

    print(
        "BM25 index created successfully."
    )

    print(
        "Total indexed documents:",
        len(
            vector_store.metadata
        ),
    )

    print(
        "Index path:",
        BM25_INDEX_PATH,
    )


# ---------------------------------------------------------------------------
# Test persisted BM25 retrieval
# ---------------------------------------------------------------------------

def test_bm25_search() -> None:
    """
    Load the persisted BM25 index and execute a test query.

    This represents the online retrieval workflow.
    """

    vector_store = BM25VectorStore()

    print(
        "Loading persisted BM25 index..."
    )

    vector_store.load()

    query = (
        "How long does it take "
        "to receive cashback?"
    )

    results = vector_store.search(
        query=query,
        top_k=3,
    )

    print(
        f"\nQuery: {query}"
    )

    print(
        f"Retrieved {len(results)} results."
    )

    for index, result in enumerate(
        results,
        start=1,
    ):

        metadata = result[
            "metadata"
        ]

        print(
            "\n" + "=" * 60
        )

        print(
            f"Result {index}"
        )

        print(
            "BM25 Score:",
            result["score"],
        )

        print(
            "Document:",
            metadata.document_name,
        )

        print(
            "Page:",
            metadata.page_number,
        )

        print(
            "Chunk ID:",
            metadata.chunk_id,
        )

        print(
            "Text:",
            result["text"],
        )


