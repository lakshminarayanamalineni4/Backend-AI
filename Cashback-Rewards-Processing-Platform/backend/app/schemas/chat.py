from pydantic import BaseModel, Field

class ChatRequest(BaseModel):
    question:str = Field(..., description="The question to be answered by the AI model.")
    
class ChatResponse(BaseModel):
    answer:str = Field(..., description="The answer generated by the AI model based on the provided context.")
    sources:list[str] = Field(..., description="A list of sources from which the answer was derived, allowing for verification of the response.")